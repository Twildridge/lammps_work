#!/usr/bin/env python3
"""screen_report.py -- assemble lammps_runs/chain_length_testing/screen_report.md (2026-11-13).

Pure standard library (runs on the login node; no numpy).  Collects, from
~/Documents/lammps_runs/chain_length_testing/screen_20261113/ :
    voids/voids_eq_<gel>.json        Part A, equilibration tail          (screen_voids.py)
    voids/voids_ref_<gel>.json       Part A metric on the Part B fixed-box reference stage
    voids/voids_eq_chk_*.json        implementation check on the compression reference stages
    runs/<gel>.run                   label|run dir|data file of each Part B run (screen_isotropy.batch)
    <run dir>/screen_isotropy_<gel>.json   G1, G2, r, A                 (screen_isotropy.py)
    jobs.txt                         jobid|purpose  (SU from sacct: AllocCPUS x elapsed hours)
    report_notes.md                  hand-written sections, appended verbatim
Usage:  python3 screen_report.py [--out <path>] [--no-sacct]
"""
import argparse
import glob
import json
import math
import os
import subprocess
import sys

HOME = os.path.expanduser("~")
SCREEN = os.path.join(HOME, "Documents/lammps_runs/chain_length_testing/screen_20261113")
REPORT = os.path.join(HOME, "Documents/lammps_runs/chain_length_testing/screen_report.md")

GELS = ["r10", "r15", "r20", "r30", "r5", "rot45_5"]
NAMES = {"r5": "random 5 (control)", "r10": "random 10", "r15": "random 15", "r20": "random 20",
         "r30": "random 30", "rot45_5": "rot45 5 (control)"}
# equilibration state, read from the logs of the existing runs on 2026-11-13
EQ_STATE = {
    "r5": "14.0 M steps, fixed length (run of 2026-11-02, no Rg halt in that deck version)",
    "r10": "24.0 M of 24 M: whole budget, Rg halt never fired (last block-to-block Rg changes 0.05-0.27 %, Rg still falling)",
    "r15": "30.0 M of 30 M: whole budget, Rg halt never fired (Rg block changes up to 0.67 % in the last 10 M)",
    "r20": "halted by the Rg plateau at 20.0 M of 35 M (plateau detected at 17.5 M; the tail block then moved 0.28 %)",
    "r30": "INCOMPLETE: wall limit at 26.703 M of 45 M, no continuation; latest state = snap9 (Rg rose 1.2 % at 18 M and 0.46 % at 24 M)",
    "rot45_5": "Rg plateau at 20.0 M, then a 20 M continuation (40 M total); the continuation's final config is the one in input_data",
}


def jload(path):
    try:
        with open(path) as fh:
            return json.load(fh)
    except (OSError, ValueError):
        return None


def fnum(v, fmt="%.3f"):
    if v is None or (isinstance(v, float) and (math.isnan(v) or math.isinf(v))):
        return "n/a"
    return fmt % v


def pm(v, e, fmt="%.4f"):
    if v is None:
        return "pending"
    return "%s ± %s" % (fnum(v, fmt), fnum(e, fmt))


def probe_rows(v):
    """list of probe dicts of a voids JSON, fixed probes first then the relative one."""
    return v["voids"]["probes"] if v and "voids" in v else []


def cell_pphi(v, i):
    rows = probe_rows(v)
    if i >= len(rows):
        return "pending"
    r = rows[i]
    return "%s / %s" % (fnum(r["empty_fraction"], "%.3f"), "skip" if r["phi"] != r["phi"] else fnum(r["phi"], "%.3f"))


def load_iso(gel):
    runf = os.path.join(SCREEN, "runs", gel + ".run")
    if not os.path.isfile(runf):
        return None, None
    with open(runf) as fh:
        parts = fh.read().strip().split("|")
    run_dir = parts[1]
    cands = sorted(glob.glob(os.path.join(run_dir, "screen_isotropy_*.json")))
    return (jload(cands[0]) if cands else None), run_dir


def sacct_su(jobids):
    out = {}
    if not jobids:
        return out
    try:
        txt = subprocess.run(["sacct", "-X", "-n", "-P", "-j", ",".join(jobids),
                              "-o", "JobID,JobName,Partition,State,ElapsedRaw,AllocCPUS,NNodes"],
                             stdout=subprocess.PIPE, universal_newlines=True, timeout=60).stdout
    except Exception:
        return out
    for ln in txt.splitlines():
        w = ln.split("|")
        if len(w) < 7:
            continue
        try:
            su = int(w[5]) * int(w[4]) / 3600.0
        except ValueError:
            su = float("nan")
        out[w[0]] = dict(name=w[1], partition=w[2], state=w[3], elapsed_s=w[4], cpus=w[5], nodes=w[6], su=su)
    return out


def build(no_sacct=False):
    L = []
    A = L.append
    eq = {g: jload(os.path.join(SCREEN, "voids", "voids_eq_%s.json" % g)) for g in GELS}
    rf = {g: jload(os.path.join(SCREEN, "voids", "voids_ref_%s.json" % g)) for g in GELS}
    iso = {}
    rundirs = {}
    for g in GELS:
        iso[g], rundirs[g] = load_iso(g)

    A("# Random-network gel screen: elastic isotropy and void persistence")
    A("")
    A("Generated by `scripts/lib/screen_report.py`; all inputs under `%s`." % SCREEN.replace(HOME, "~"))
    A("")
    notes_top = os.path.join(SCREEN, "report_summary.md")
    if os.path.isfile(notes_top):
        A(open(notes_top).read().rstrip())
        A("")

    # ---------------- main table ----------------
    A("## 1. One row per gel")
    A("")
    A("Cells under r_p are `empty fraction / Phi`; first line = equilibration tail (Part A), second = "
      "fixed-box reference stage of the Part B run. G1, G2, r, A from the polymer-group stress "
      "(whole-box values in section 4); ± = block standard error (50k-step blocks).")
    A("")
    hdr = ["gel", "beads per strand (bonds n)", "equilibration state", "polymer density (interior)",
           "mesh size <R_ee>", "chord ext. <R/(n b)> (CV)", "r_p = 1.0", "r_p = 1.5", "r_p = 2.5",
           "r_p = 0.4 <R_ee>", "G1", "G2", "r = G1/G2", "A"]
    A("| " + " | ".join(hdr) + " |")
    A("|" + "---|" * len(hdr))
    for g in GELS:
        s = eq[g]["statics"] if eq[g] and "statics" in eq[g] else None
        row = [NAMES[g]]
        if s:
            n = s["bonds_per_strand_mode"]
            row.append("%d (n = %d)" % (n + 1, n))
        else:
            row.append("pending")
        row.append(EQ_STATE[g])
        if s:
            row.append(fnum(s["rho_polymer_interior"], "%.4f"))
            row.append(fnum(s["interior"]["R_mean"], "%.2f"))
            row.append("%s (%s)" % (fnum(s["interior"]["ext_mean"], "%.3f"), fnum(s["interior"]["ext_cv"], "%.2f")))
        else:
            row += ["pending"] * 3
        for i in range(4):
            c = "eq %s<br>ref %s" % (cell_pphi(eq[g], i), cell_pphi(rf[g], i))
            if i == 3 and eq[g] and "rel_probe" in eq[g]:
                c = "(r_p = %.2f)<br>" % eq[g]["rel_probe"]["r_p"] + c
            row.append(c)
        p = iso[g]["poly"] if iso[g] and "poly" in iso[g] else {}
        row.append(pm(p.get("G1"), p.get("G1_err")))
        row.append(pm(p.get("G2"), p.get("G2_err")))
        row.append(pm(p.get("r"), p.get("r_err"), "%.3f"))
        row.append(pm(p.get("A"), p.get("A_err"), "%.3f"))
        A("| " + " | ".join(row) + " |")
    A("")

    # ---------------- frames / drift ----------------
    A("## 2. Part A details: frames used and drift over them")
    A("")
    A("| gel | source | frames | step range | spacing | lx first -> last (%) | ly first -> last (%) | "
      "thickness (crosslinker extent) first -> last (%) | sqrt(12) Rg_z first -> last (%) |")
    A("|---|---|---|---|---|---|---|---|---|")
    for src, dd in (("equilibration tail", eq), ("Part B reference (fixed box)", rf)):
        for g in GELS:
            v = dd[g]
            if not v or "voids" not in v:
                continue
            vo, dr = v["voids"], v["drift"]

            def d(k):
                x = dr[k]
                return "%.3f -> %.3f (%+.2f)" % (x["first"], x["last"], x["change_pct"])
            A("| %s | %s | %d of %d | %d .. %d | %d | %s | %s | %s | %s |"
              % (NAMES[g], src, vo["n_frames"], v.get("frames_in_file", vo["n_frames"]), vo["step_first"],
                 vo["step_last"], vo["frame_spacing"], d("lx"), d("ly"), d("thick_xl"), d("thick_rg")))
    A("")
    A("First / last = mean of the first / last tenth of the frames used. The crosslinker extent is a "
      "min/max of single atoms (noisy to ~0.5 sigma); sqrt(12) Rg_z of the polymer is the smooth thickness measure.")
    A("")

    # ---------------- Phi vs window ----------------
    A("## 3. Phi against window length (last w frames) and two-time overlap")
    A("")
    for src, dd in (("Equilibration tail (frames 100k steps apart)", eq), ("Part B reference stage, fixed box (frames 10k steps apart)", rf)):
        any_ = [g for g in GELS if dd[g] and "voids" in dd[g]]
        if not any_:
            continue
        A("### %s" % src)
        A("")
        for g in any_:
            vo = dd[g]["voids"]
            wins = [w["frames"] for w in vo["probes"][0]["windows"]]
            A("**%s** — Phi over the last w frames (span in steps):" % NAMES[g])
            A("")
            A("| r_p | empty fraction | " + " | ".join("w = %d (%s)" % (w["frames"], _k(w["span_steps"])) for w in vo["probes"][0]["windows"]) + " |")
            A("|---|---|" + "---|" * len(wins))
            for pr in vo["probes"]:
                A("| %.2f | %s | " % (pr["r_p"], fnum(pr["empty_fraction"], "%.4f")) +
                  " | ".join("skip" if w["phi"] != w["phi"] else "%.3f" % w["phi"] for w in pr["windows"]) + " |")
            A("")
            lagrows = [pr for pr in vo["probes"] if pr["lags"]]
            if lagrows:
                A("Two-time overlap C(lag) = (<emp(t) emp(t+lag)> - p^2) / (p (1 - p)):")
                A("")
                A("| r_p | " + " | ".join("lag %s" % _k(l["lag_steps"]) for l in lagrows[0]["lags"]) + " |")
                A("|---|" + "---|" * len(lagrows[0]["lags"]))
                for pr in lagrows:
                    A("| %.2f | " % pr["r_p"] + " | ".join("%.3f" % l["overlap"] for l in pr["lags"]) + " |")
                A("")

    # ---------------- isotropy detail ----------------
    A("## 4. Part B details: stresses and moduli, both stress measures")
    A("")
    have = [g for g in GELS if iso[g]]
    if not have:
        A("No Part B results on disk yet.")
        A("")
    else:
        A("| gel | stress | G1 | G2 | r | A | G1 one-sided (+ / -) | G2 one-sided (+ / -) | rel. err. on r |")
        A("|---|---|---|---|---|---|---|---|---|")
        for g in have:
            for key, nm in (("poly", "polymer group"), ("box", "whole box")):
                p = iso[g].get(key, {})
                A("| %s | %s | %s | %s | %s | %s | %s / %s | %s / %s | %s |"
                  % (NAMES[g], nm, pm(p.get("G1"), p.get("G1_err")), pm(p.get("G2"), p.get("G2_err")),
                     pm(p.get("r"), p.get("r_err"), "%.3f"), pm(p.get("A"), p.get("A_err"), "%.3f"),
                     fnum(p.get("G1_plus"), "%.4f"), fnum(p.get("G1_minus"), "%.4f"),
                     fnum(p.get("G2_plus"), "%.4f"), fnum(p.get("G2_minus"), "%.4f"),
                     "%.0f %%" % (100 * p["r_rel_err"]) if "r_rel_err" in p else "pending"))
        A("")
        A("Hold averages (tension-positive stress per gel volume; mean ± block s.e.; ref = zero-strain baseline, "
          "`*_hold_0` = after the return to zero strain):")
        A("")
        A("| gel | stage | gamma = xy/ly | e_x | sigma_xy poly | sigma_xy box | (sxx-syy) poly | (sxx-syy) box |")
        A("|---|---|---|---|---|---|---|---|")
        for g in have:
            r = iso[g]
            for s in r.get("holds_available", []):
                hp, hb = r["poly"]["holds"][s], r["box"]["holds"][s]
                A("| %s | %s | %+.5f | %+.5f | %s | %s | %s | %s |"
                  % (NAMES[g], s, r["strain"][s]["gamma"], r["strain"][s]["e_x"],
                     pm(hp["sxy"]["mean"], hp["sxy"]["sem"], "%+.2e"), pm(hb["sxy"]["mean"], hb["sxy"]["sem"], "%+.2e"),
                     pm(hp["nd"]["mean"], hp["nd"]["sem"], "%+.2e"), pm(hb["nd"]["mean"], hb["nd"]["sem"], "%+.2e")))
        A("")
        A("| gel | run dir | complete | last step | box lx0 x ly0 x lz | gel thickness (polymer bbox / crosslinkers) | V_gel | T mobile | <P> |")
        A("|---|---|---|---|---|---|---|---|---|")
        for g in have:
            r = iso[g]
            ge, th = r["geometry"], r.get("thermo", {})
            A("| %s | `%s` | %s | %d | %.3f x %.3f x %.3f | %.2f / %.2f | %.0f | %s | %s |"
              % (NAMES[g], os.path.basename(r["run_dir"]), "yes" if r["complete"] else "NO", r["last_step_on_disk"],
                 ge["lx0"], ge["ly0"], ge["lz0"], ge["thickness_polymer_bbox"], ge["thickness_xlink"], ge["V_gel"],
                 fnum(th.get("T_mobile_mean"), "%.4f"), fnum(th.get("press_mean"), "%.3f")))
        A("")

    # ---------------- implementation check ----------------
    A("## 5. Control checks")
    A("")
    A("### 5a. Void-metric implementation against the reference numbers")
    A("")
    A("16 frames, 150k steps, reference stage of the compression runs (`traj_ref_final_config_*`). "
      "Target: random 5 -> Phi 0.31-0.33 at r_p 1.0-1.5, empty fraction 0.14 at r_p 1.0; "
      "rot45 5 -> Phi 0.01-0.05, empty fraction 0.24 at r_p 1.0.")
    A("")
    A("| trajectory | frames | steps | r_p | empty fraction | Phi |")
    A("|---|---|---|---|---|---|")
    for lab, nm in (("chk_r5", "random 5, compression ref"), ("chk_rot45_5", "rot45 5, compression ref")):
        v = jload(os.path.join(SCREEN, "voids", "voids_eq_%s.json" % lab))
        if not v or "voids" not in v:
            A("| %s | pending | | | | |" % nm)
            continue
        vo = v["voids"]
        for pr in vo["probes"]:
            A("| %s | %d | %d .. %d | %.2f | %s | %s |" % (nm, vo["n_frames"], vo["step_first"], vo["step_last"], pr["r_p"],
                                                          fnum(pr["empty_fraction"], "%.4f"),
                                                          "skip" if pr["phi"] != pr["phi"] else "%.3f" % pr["phi"]))
    A("")
    for name in ("report_controls.md", "report_notes.md"):
        p = os.path.join(SCREEN, name)
        if os.path.isfile(p):
            A(open(p).read().rstrip())
            A("")

    # ---------------- jobs ----------------
    A("## 7. Jobs and SU")
    A("")
    jobs = []
    jf = os.path.join(SCREEN, "jobs.txt")
    if os.path.isfile(jf):
        for ln in open(jf):
            w = ln.strip().split("|")
            if len(w) >= 2 and w[0]:
                jobs.append((w[0], w[1]))
    acct = {} if no_sacct else sacct_su([j for j, _ in jobs])
    A("| job | purpose | partition | nodes | cores | state | elapsed (s) | SU (cores x hours) |")
    A("|---|---|---|---|---|---|---|---|")
    tot = 0.0
    for j, what in jobs:
        a = acct.get(j)
        if a:
            if a["su"] == a["su"]:
                tot += a["su"]
            A("| %s | %s | %s | %s | %s | %s | %s | %.1f |" % (j, what, a["partition"], a["nodes"], a["cpus"], a["state"], a["elapsed_s"], a["su"]))
        else:
            A("| %s | %s | | | | (no sacct record) | | |" % (j, what))
    A("")
    A("Total so far: **%.0f SU** of the 8,000 SU budget (running jobs counted up to now)." % tot)
    A("")
    files = os.path.join(SCREEN, "report_files.md")
    if os.path.isfile(files):
        A(open(files).read().rstrip())
        A("")
    return "\n".join(L) + "\n"


def _k(steps):
    if steps >= 1000000:
        return "%.2gM" % (steps / 1e6)
    return "%dk" % round(steps / 1000.0)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", default=REPORT)
    ap.add_argument("--no-sacct", action="store_true")
    a = ap.parse_args(argv)
    txt = build(a.no_sacct)
    with open(a.out, "w") as fh:
        fh.write(txt)
    print("wrote %s (%d lines)" % (a.out, txt.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
